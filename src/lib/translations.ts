export function translate(
  language: Language,
  text: string,
  values: unknown[] = [],
): string {
  const translated = language === "nb" ? (norwegian[text] ?? text) : text;
  return translated.replace(/\{(\d+)\}/g, (match, index: string) =>
    String(values[Number(index)] ?? match),
  );
}
